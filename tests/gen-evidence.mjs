#!/usr/bin/env node
/**
 * Regenerate the machine-readable evidence under evidence/.
 *
 * Dependency-free: node tests/gen-evidence.mjs
 *
 * Every file written here is EVIDENCE about what has and has not been observed.
 * Nothing in evidence/ may claim a host capability the runtime cannot
 * demonstrate, so each artifact carries an explicit status and provenance line
 * (pack §46/§55/§57/§68). The v0.1 runtime ships no host mapping at all, so
 * the honest content of `adapter-status.json` is a set of BLOCKED entries.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createDocument, parseHTML, serialize } from './lib/mini-dom.mjs';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, 'evidence');
const RUNTIME = join(root, 'github-dev-mobile.user.js');
const RECON = join(root, 'gmux-recon.user.js');

const R = require(RECON);
delete require.cache[require.resolve(RUNTIME)];
const K = require(RUNTIME);

const generatedAt = new Date().toISOString();
const harnessProvenance =
  'generated by tests/gen-evidence.mjs in a Node miniature-DOM harness; ' +
  'NOT a live github.dev session and NOT an Android device — UNVALIDATED_LIVE';

function docFrom(html) {
  const doc = createDocument({});
  const parsed = parseHTML(html, doc);
  while (parsed.children.length) doc.body.appendChild(parsed.children[0]);
  const mark = (el) => { if (el.tagName !== 'BODY') el.setAttribute('data-rect', '4:120:48:48'); el.children.forEach(mark); };
  mark(doc.body);
  return doc;
}

/* --------------------------- 1. reconnaissance -------------------------- */
const fixtureDir = join(root, 'fixtures');
const htmlFixtures = readdirSync(fixtureDir).filter((f) => f.endsWith('.html')).sort();
const payloads = htmlFixtures.map((file) => {
  const doc = docFrom(readFileSync(join(fixtureDir, file), 'utf8'));
  const payload = R.buildReconPayload(doc, {
    environment: { width: 412, height: 915, touchPoints: 5, coarsePointer: true },
    timestamp: generatedAt,
  });
  return {
    fixture: `fixtures/${file}`,
    schema: payload.schema,
    candidateCount: payload.candidates.length,
    bySurface: payload.bySurface,
    discovery: payload.discovery,
    candidates: payload.candidates.map((c) => ({
      surface: c.surface, tag: c.tag, name: c.ariaLabel || c.title || c.snippet,
      strategy: c.strategy, visible: c.visible, confidence: c.confidence,
    })),
    interpretation: payload.interpretation,
  };
});

/** Privacy assertion re-run here so the evidence file cannot drift from the rule. */
const CONTENT_SENTINELS = ['repository.rs', 'SECRETCODELINE', 'ghp_LEAK', 'TERMINAL_OUTPUT', 'rm -rf', 'passwd'];
const leakScan = JSON.stringify(payloads);
const leaked = CONTENT_SENTINELS.filter((s) => leakScan.includes(s));

writeFileSync(join(out, 'reconnaissance.json'), JSON.stringify({
  schema: 'gmux.evidence/recon-run/v1',
  generatedAt,
  provenance: harnessProvenance,
  instrument: 'gmux-recon.user.js',
  host: 'github.dev',
  inputs: payloads.map((p) => p.fixture),
  privacyBoundary: {
    sentinelsSearched: CONTENT_SENTINELS,
    leaked: leaked,
    status: leaked.length === 0 ? 'PASS (harness fixtures)' : 'FAIL',
    note: 'repository contents, file contents, terminal output, commit messages, credentials, cookies and storage are never collected (§43)',
  },
  payloads,
  reading: 'candidate structure only — see §46/§47. Promotion requires the §50 review chain.',
}, null, 2) + '\n');

/* --------------------------- 2. adapter status -------------------------- */
const surfaces = ['editor', 'explorer', 'search', 'sourceControl', 'terminal'];
writeFileSync(join(out, 'adapter-status.json'), JSON.stringify({
  schema: 'gmux.evidence/adapter-status/v1',
  generatedAt,
  provenance: harnessProvenance,
  gmuxVersion: K.VERSION,
  adapter: { id: K.GitHubDevAdapter.id, revision: K.GitHubDevAdapter.revision },
  // §56: GMUX version and adapter revision move independently.
  independenceNote: 'gmuxVersion tracks the runtime; adapter.revision tracks host mappings only.',
  mappingCount: 0,
  mappingPolicy: 'v0.1 forbids guessed GitHub selectors in the runtime (§12/§13/§72); the registry is empty by design.',
  surfaces: surfaces.reduce((acc, surface) => {
    const resolved = K.GitHubDevAdapter.resolveSurface(surface);
    const found = K.GitHubDevAdapter[`find${surface[0].toUpperCase()}${surface.slice(1)}`]();
    acc[surface] = {
      status: resolved.status,
      reason: resolved.reason,
      hostLookupReturned: found === null ? 'null' : typeof found,
      confidence: K.CONFIDENCE.UNKNOWN,
      operational: false,
      verified: false,
    };
    return acc;
  }, {}),
  hostFingerprint: K.hostFingerprint(K.observeSurfaces(K.GitHubDevAdapter).records),
  driftEvents: [],
  promotionRequirements: [
    'live reconnaissance (GMUXRecon.run) produces candidates (§44–§47)',
    'a human reviews them into an adapter definition (§50)',
    'a fixture is frozen per surface (§53) and the golden-state invariant passes (§54)',
    'mutation tests degrade rather than falsely verify (§55)',
    'only then may adapterRevision become 1 and a surface report VERIFIED',
  ],
}, null, 2) + '\n');

/* ------------------------- 3. mutation results ------------------------- */
const MUTATIONS = {
  'aria-label changed': (doc) => doc.querySelector('[aria-label="Explorer"]')?.setAttribute('aria-label', 'File Browser'),
  'button removed': (doc) => doc.querySelector('[aria-label="Explorer"]')?.remove(),
  'container moved': (doc) => { const t = doc.querySelector('.part.sidebar'); if (t) doc.querySelector('.part.editor')?.appendChild(t); },
  'panel renamed': (doc) => doc.querySelector('.part.sidebar')?.setAttribute('aria-label', 'Repository View'),
  'visibility changed': (doc) => { const el = doc.querySelector('[aria-label="Explorer"]'); if (el) el.hidden = true; },
  'duplicate candidate added': (doc) => { const b = doc.createElement('button'); b.setAttribute('aria-label', 'Explorer'); doc.querySelector('.monaco-workbench')?.appendChild(b); },
  'role changed': (doc) => doc.querySelector('[aria-label="Explorer"]')?.setAttribute('role', 'treeitem'),
  'irrelevant candidate added': (doc) => { const b = doc.createElement('button'); b.setAttribute('aria-label', 'Banana'); doc.querySelector('.monaco-workbench')?.appendChild(b); },
};
const baseDoc = docFrom(readFileSync(join(fixtureDir, 'baseline.html'), 'utf8'));
const baseline = R.buildReconPayload(baseDoc, { environment: { width: 412, height: 915, touchPoints: 5, coarsePointer: true } });
const mutationResults = Object.entries(MUTATIONS).map(([name, mutate]) => {
  const doc = docFrom(readFileSync(join(fixtureDir, 'baseline.html'), 'utf8'));
  mutate(doc);
  const p = R.buildReconPayload(doc, { environment: { width: 412, height: 915, touchPoints: 5, coarsePointer: true } });
  const json = JSON.stringify(p);
  const explorerCandidates = p.candidates.filter((c) => c.surface === 'explorer' && c.visible);
  return {
    mutation: name,
    candidatesBefore: baseline.candidates.length,
    candidatesAfter: p.candidates.length,
    explorerCandidatesAfter: explorerCandidates.length,
    claimedVerified: /"VERIFIED"/.test(json),
    claimedOperational: p.candidates.some((c) => c.operational === true || c.verified === true),
    skipped: p.discovery.skipped,
    outcome: p.candidates.every((c) => c.confidence === 'candidate') && !/"VERIFIED"/.test(json)
      ? 'DEGRADED — candidate evidence only, no capability claim (§55 expectation met)'
      : 'UNEXPECTED — a false claim appeared',
  };
});
writeFileSync(join(out, 'mutation-results.json'), JSON.stringify({
  schema: 'gmux.evidence/mutation/v1',
  generatedAt,
  provenance: harnessProvenance,
  baseline: { fixture: 'fixtures/baseline.html', candidates: baseline.candidates.length },
  expectation: 'mutation → adapter uncertainty → PROVISIONAL / BLOCKED; never mutation → false VERIFIED (§55)',
  results: mutationResults,
  allDegraded: mutationResults.every((r) => !r.claimedVerified && !r.claimedOperational),
}, null, 2) + '\n');

/* --------------------------- 4. fixture index --------------------------- */
const gdDir = join(fixtureDir, 'github-dev');
const fixtures = readdirSync(gdDir).filter((f) => f.endsWith('.json')).sort().map((file) => {
  const fx = JSON.parse(readFileSync(join(gdDir, file), 'utf8'));
  return {
    file: `fixtures/github-dev/${file}`,
    schema: fx.schema,
    surface: fx.surface,
    state: fx.state,
    elements: fx.elements.length,
    status: fx.status,
    verification: fx.verification,
  };
});
writeFileSync(join(out, 'fixtures-index.json'), JSON.stringify({
  schema: 'gmux.evidence/fixtures-index/v1',
  generatedAt,
  provenance: harnessProvenance,
  count: fixtures.length,
  format: 'role + accessible name only; no CSS selectors (§51/§53)',
  usage: 'Phase C adapter verification inputs. They are expectation records, not live captures.',
  fixtures,
}, null, 2) + '\n');

console.log('evidence written:');
for (const f of ['reconnaissance.json', 'adapter-status.json', 'mutation-results.json', 'fixtures-index.json']) {
  const bytes = readFileSync(join(out, f), 'utf8').length;
  console.log(`  evidence/${f} (${bytes} bytes)`);
}
console.log(`fixtures scanned: ${htmlFixtures.length} · candidates total: ${payloads.reduce((n, p) => n + p.candidateCount, 0)}`);
console.log(`privacy sentinels leaked: ${leaked.length}`);
console.log(`mutations all degraded safely: ${mutationResults.every((r) => !r.claimedVerified && !r.claimedOperational)}`);
if (leaked.length) process.exitCode = 1;
